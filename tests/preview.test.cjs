const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const M=require('../model.js');
const base=path.resolve(__dirname,'..');
const initial=M.initial();
assert.equal(initial.page,'overview');
assert.equal(M.REVENUE.length,6);
assert.equal(M.EXPENSES.length,6);
assert.equal(M.money(45231890),'TZS 45,231,890');
assert.equal(M.byType(initial.returns,'VAT').length,3);
assert.equal(M.unread(initial.notifications),2);
assert.equal(M.validateDemoFile({name:'malware.exe'}),'Use CSV, Excel, PDF or image files.');
assert.equal(M.validateDemoFile({name:'statement.csv',size:11*1024*1024}),'Files must be 10 MB or smaller.');
const add=M.addDemoDocument(initial,{name:'example.csv',size:100000});
assert.equal(add.error,null);assert.equal(add.state.documents.length,initial.documents.length+1);
assert.equal(add.state.documents[0].status,'processed');
const bad=M.submitReturn(initial,'BAD'); assert.ok(bad.error);
const changed=M.submitReturn(initial,'VAT-2403');assert.equal(changed.state.returns.find(x=>x.id==='VAT-2403').status,'submitted-demo');
assert.equal(M.submitReturn(changed.state,'VAT-2403').error,'Only sample drafts can be changed.');
const created=M.generateReport(initial,'financial','Q2 2024');assert.equal(created.state.reports.length,initial.reports.length+1);assert.match(created.report.name,/demo/i);
assert.equal(M.generateReport(initial,'wrong','Q2 2024').error,'Choose a report type.');
assert.equal(M.safeText('<img onerror="x">'),'&lt;img onerror=&quot;x&quot;&gt;');
for(const file of ['index.html','app.js','model.js','styles.css','favicon.svg','README.md'])assert.ok(fs.existsSync(path.join(base,file)),file);
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
assert.ok(/app\.js/.test(html) && /styles\.css/.test(html));
assert.ok(!/<input[^>]*type=['"]?password/i.test(html));
const app=fs.readFileSync(path.join(base,'app.js'),'utf8');
for(const page of ['overview','upload','returns','reports','notifications','settings']) assert.ok(app.includes(page),page);
assert.ok(!/https?:\/\/(?:127\.0\.0\.1|localhost)|supabase\.co|fetch\(/.test(app),'preview must not use production/local APIs');
console.log('Fahari light-mode preview: 20 checks passed.');
